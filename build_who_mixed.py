def en_exists(rel: str) -> bool:
    """Does build_en.py produce /en/<rel>? rel is the site-relative directory:
    "" for the home, "track/", "track/<slug>/", "faq/". Redirect stubs are
    rendered by render_redirect (no hreflang) and never reach this check."""
    if not EMIT_EN:
        return False
    return rel in EN_STATIC or bool(re.fullmatch(r"track/[^/]+/", rel))


def hreflang_links(rel: str) -> str:
    """<link rel=alternate hreflang> block for a RU page, or "" if no EN twin."""
    if not en_exists(rel):
        return ""
    ru, en = f"{SITE}/{rel}", f"{SITE}/en/{rel}"
    return (
        f'<link rel="alternate" hreflang="ru" href="{ru}">\n'
        f'<link rel="alternate" hreflang="en" href="{en}">\n'
        f'<link rel="alternate" hreflang="x-default" href="{en}">\n'
    )


HREFLANG_RE = re.compile(r'\n?<link rel="alternate" hreflang="[^"]*" href="[^"]*"\s*/?>')


def patch_hreflang(doc: str, rel: str) -> str:
    """Hand-written pages (index.html, faq/index.html): drop whatever hreflang
    links are there and re-emit the current set right after the canonical —
    the same anchor build_en.py uses on the EN side, so the two mirror."""
    doc = HREFLANG_RE.sub("", doc)
    links = hreflang_links(rel)
    if not links:
        return doc
    return re.sub(r'(<link rel="canonical" href="[^"]*">)',
                  lambda m: m.group(1) + "\n" + links.rstrip("\n"), doc, count=1)

TRANSLIT = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "yo",
    "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "h", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "sch",
    "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}


def esc(s: str) -> str:
    return html.escape(s, quote=True)


def slugify(*parts: str) -> str:
    raw = "-".join(parts).lower().replace("’", "'")
    out = []
    for ch in raw:
        if ch in TRANSLIT:
            out.append(TRANSLIT[ch])
        elif "a" <= ch <= "z" or "0" <= ch <= "9":
            out.append(ch)
        elif ch in " -_'/;,&.+":
            out.append("-")
    slug = re.sub(r"-+", "-", "".join(out)).strip("-")
    return slug[:80] or "track"


def canon(name: str) -> str:
    """Canonical display name for a single artist token."""
    n = name.replace("*", "").strip()
    return CANON.get(n, n)


def is_ia(name: str) -> bool:
    return name.replace("*", "").strip().lower() in IA


def primary_of(artist: str) -> str:
    return canon(artist.split(", ")[0])


def others_of(artist: str) -> list[str]:
    return [canon(x) for x in artist.split(", ")[1:]]


def feat_of(tr: dict) -> list[str]:
    """Per-track featured artists. Album tracks: explicit `feat` field
    (string or list). Singles: fall back to non-primary artists in `artist`."""
    f = tr.get("feat")
    if f:
        names = [f] if isinstance(f, str) else list(f)
        return [canon(x) for x in names if x]
    return [] if tr.get("album") else others_of(tr["artist"])


