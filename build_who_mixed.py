def _artist_sort_key(name: str):
    """Latin A–Z first, then Cyrillic А–Я, then digits/other."""
    cl = (name[:1] or "").lower()
    if "a" <= cl <= "z":
        bucket = 0
    elif "а" <= cl <= "я" or cl == "ё":
        bucket = 1
    else:
        bucket = 2
    return (bucket, name.lower())


def _dq(*parts: str) -> str:
    return esc(" ".join(p for p in parts if p).lower())


