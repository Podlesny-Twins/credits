def patch_index_footer(doc: str, tracks: list[dict]) -> str:
    css = """
.pf .seo-foot{margin:22px auto 0;font-size:12px;line-height:1.5}
.pf .seo-foot a{color:#918b8b;font-weight:600}
.pf .seo-foot a:hover{color:#cfc9c9}
"""
    if ".pf .seo-foot" not in doc:
        doc = doc.replace("</style>", css + "</style>", 1)

    # The home-page footer links out to the catalogue, the FAQ, and the
    # studio's Telegram channel + chat. Replace the whole <p class="seo-foot">
    # in place (idempotent) so re-runs update it instead of duplicating.
    foot = ('<p class="seo-foot"><a href="/track/">Полный список треков</a>'
            ' · <a href="/faq/">Вопросы и ответы</a>'
            ' · <a href="/tier/">Тир-лист техник сведения</a>'
            ' · <a href="https://t.me/lesnymix" rel="noopener">Канал о звуке</a>'
            ' · <a href="https://t.me/+VXgXHnAXj9w2ZGYy" rel="noopener">Чат</a></p>')
    if 'class="seo-foot"' in doc:
        doc = re.sub(r'<p class="seo-foot">.*?</p>', foot, doc, count=1, flags=re.S)
    else:
        doc = doc.replace('<p class="iadisc">', foot + "\n    " + '<p class="iadisc">', 1)

    # One source of truth for the card-side story viewer. Only works that
    # actually have a story are listed: the modal never opens without one.
    #
    # The texts (≈140 KB) live in /track-info.json, not inline — the grid is
    # the page's whole promise and pays for its own weight; the stories are
    # fetched once the page is idle, long before anyone opens one. Inline
    # stays the id list, so the ⓘ buttons can be placed on first paint.
    track_info = {
        tr["id"]: {
            "slug": tr["slug"],
            "artist": tr["artist"],
            "title": tr["title"],
            "year": tr.get("year", ""),
            "role": ROLE_WORD.get(tr["role"], "Сведение"),
            "notes": notes_for(tr),
            "url": f"/track/{tr['slug']}/",
            "image": tr.get("img", ""),
        }
        for tr in tracks
        if notes_for(tr)
    }
    (ROOT / "track-info.json").write_text(
        json.dumps(track_info, ensure_ascii=False, separators=(",", ":")) + "\n",
        encoding="utf-8",
    )

    ids = json.dumps(sorted(track_info), separators=(",", ":"))
    data_tag = f'<script type="application/json" id="track-story-ids">{ids}</script>'
    doc = re.sub(                       # the earlier inline payload, if present
        r'<script type="application/json" id="track-info-data">.*?</script>\n?',
        "",
        doc,
        count=1,
        flags=re.S,
    )
    if 'id="track-story-ids"' in doc:
        doc = re.sub(
            r'<script type="application/json" id="track-story-ids">.*?</script>',
            data_tag,
            doc,
            count=1,
            flags=re.S,
        )
    else:
        doc = doc.replace(
            '<script src="https://open.spotify.com/embed/iframe-api/v1" async></script>',
            data_tag + '\n<script src="https://open.spotify.com/embed/iframe-api/v1" async></script>',
            1,
        )
    doc = patch_index_roles(doc, tracks)
    return patch_hreflang(doc, "")


# ── home page: role-accurate alts + JSON-LD catalogue ────────────────
#
# add_track.py writes every new tile with the generic «сведение и мастеринг»
# alt, and the home-page JSON-LD was maintained by hand (it had drifted: 8
# singles and one album missing, every Role claiming both jobs). roles.json is
# the only place a role is recorded, so both are rewritten from it here on
# every build — the alt tail and the Role.roleName can no longer over-claim.

LD_BYLINE = "Podlesny Twins (Павел Подлесный и Антон Подлесный)"


def _studio_role(role: str) -> dict:
    return {"@type": "Role", "roleName": ROLE_NAME_LD[role],
            "contributor": {"@id": STUDIO_ID}}


def _recording_ld(tr: dict, with_description: bool) -> dict:
    node = {
        "@type": "MusicRecording",
        "name": tr["title"],
        "url": f"{SITE}/track/{tr['slug']}/",
        "byArtist": {"@type": "MusicGroup", "name": tr["artist"]},
        "contributor": _studio_role(tr["role"]),
    }
    if with_description:
        node["description"] = f"{ROLE_WORD[tr['role']]} — {LD_BYLINE}."
    return node


def _album_roles(album: dict, by_id: dict) -> set[str]:
    return {by_id[t["id"]]["role"] for t in album["tracks"] if t["id"] in by_id}


def patch_index_roles(doc: str, tracks: list[dict]) -> str:
    by_id = {tr["id"]: tr for tr in tracks}
    albums = json.loads(re.search(r"var ALBUMS=(\[.*?\]);", doc, re.S).group(1))

    # 1. cover alts. Single: «Artist — Title · <role> Podlesny Twins».
    #    Album: same with «(альбом)» when every track shares one role; a
    #    release with mixed roles names the cover and claims nothing.
    def single_alt(m: re.Match) -> str:
        tid = m.group(2)
        tr = by_id.get(tid)
        if tr is None:
            return m.group(0)
        alt = f"{tr['artist']} — {tr['title']} · {ROLE_ALT[tr['role']]}"
        return f"{m.group(1)}{esc(alt)}{m.group(3)}"

    doc = re.sub(
        r'(<button class="tile(?![^"]*album)[^"]*"[^>]*data-id="([A-Za-z0-9]{22})"'
        r'[^>]*>\s*<img src="[^"]+" alt=")[^"]*(")',
        single_alt, doc,
    )

    def album_alt(m: re.Match) -> str:
        album = albums[int(m.group(2))]
        roles = _album_roles(album, by_id)
        head = f"{album['artist']} — {album['name']} (альбом)"
        tail = ROLE_ALT[roles.pop()] if len(roles) == 1 else MIXED_ALT
        return f"{m.group(1)}{esc(f'{head} · {tail}')}{m.group(3)}"

    doc = re.sub(
        r'(<button class="tile album"[^>]*onclick="openAlbum\((\d+)\)"[^>]*>\s*'
        r'<img src="[^"]+" alt=")[^"]*(")',
        album_alt, doc,
    )

    # 2. JSON-LD: studio entity (normalised) + founders, then the catalogue
    #    regenerated from the tiles, so it lists exactly what the page shows.
    ld_re = re.compile(r'(<script type="application/ld\+json">)(.*?)(</script>)', re.S)
    m = ld_re.search(doc)
    if not m:
        raise SystemExit("index.html: JSON-LD block not found")
    graph = json.loads(m.group(2))["@graph"]
    head = fix_studio_graph([n for n in graph if n.get("@type") not in ("MusicRecording", "MusicAlbum")])

    catalogue: list[dict] = []
    for tr in tracks:
        if not tr.get("album"):
            catalogue.append(_recording_ld(tr, with_description=True))
    for album in albums:
        roles = _album_roles(album, by_id)
        node = {
            "@type": "MusicAlbum",
            "name": album["name"],
            "byArtist": {"@type": "MusicGroup", "name": album["artist"]},
        }
        if len(roles) == 1:
            role = next(iter(roles))
            node["contributor"] = _studio_role(role)
            node["description"] = f"{ROLE_WORD[role]} — {LD_BYLINE}."
        else:
            node["description"] = f"Роль студии указана по каждому треку — {LD_BYLINE}."
        node["track"] = [
            _recording_ld(by_id[t["id"]], with_description=False)
            for t in album["tracks"] if t["id"] in by_id
        ]
        catalogue.append(node)

    ld = json.dumps({"@context": "https://schema.org", "@graph": head + catalogue},
                    ensure_ascii=False)
    return doc[: m.start(2)] + ld + doc[m.end(2):]


# ── FAQ + llms.txt: counters and the studio entity from one source ───
#
# Both files are hand-written, so the figures used to be typed in and went
# stale (214/69 against a 217-track catalogue). The numbers now live in
# <span data-n="works|artists"> markers in the FAQ and in one fixed phrase
# in llms.txt; the build rewrites them from catalog_counts() and refuses to
# continue if a marker disappeared — a silent miss is how they drifted.

FAQ_FILE = ROOT / "faq" / "index.html"
LLMS_FILE = ROOT / "llms.txt"


def _sub_counted(text: str, pattern: str, repl, label: str, min_hits: int = 1) -> str:
    out, n = re.subn(pattern, repl, text)
    if n < min_hits:
        raise SystemExit(f"{label}: expected ≥{min_hits} counter marker(s), found {n}")
    return out


def patch_faq(counts: dict) -> None:
    src = FAQ_FILE.read_text(encoding="utf-8")
    for key, value in (("works", counts["recordings"]), ("artists", counts["artists"])):
        src = _sub_counted(
            src, rf'(<span(?=[^>]*\bdata-n="{key}")[^>]*>)\d+(</span>)',
            rf"\g<1>{value}\g<2>", f"faq/index.html data-n={key}",
        )
    ld_re = re.compile(r'(<script type="application/ld\+json">)(.*?)(</script>)', re.S)
    m = ld_re.search(src)
    if not m:
        raise SystemExit("faq/index.html: JSON-LD block not found")
    data = json.loads(m.group(2))
    data["@graph"] = fix_studio_graph(data["@graph"])
    src = src[: m.start(2)] + json.dumps(data, ensure_ascii=False) + src[m.end(2):]
    src = patch_hreflang(src, "faq/")
    FAQ_FILE.write_text(src, encoding="utf-8")
    # the FAQPage answers are copies of the visible text — rebuild them now
    # so the counters just written land in the schema in the same run
    import sync_faq_schema
    if sync_faq_schema.main() != 0:
        raise SystemExit("sync_faq_schema failed")


def patch_llms_txt(counts: dict) -> None:
    src = LLMS_FILE.read_text(encoding="utf-8")
    src = _sub_counted(
        src, r"\d+ избранных работ для \d+ артистов",
        f"{counts['recordings']} избранных работ для {counts['artists']} артистов",
        "llms.txt",
    )
    en_line = (f"- [English version](https://credits.podlesnytwins.com/en/): "
               f"страницы на английском; сводка для ИИ — {SITE}/en/llms.txt")
    if en_exists("") and "/en/llms.txt" not in src:
        anchor = f"- [llms-full.txt]({SITE}/llms-full.txt)"
        i = src.find(anchor)
        if i < 0:
            raise SystemExit("llms.txt: «Полный контент» anchor line not found")
        j = src.find("\n", i)
        src = src[: j + 1] + en_line + "\n" + src[j + 1:]
    LLMS_FILE.write_text(src, encoding="utf-8")


# ── SEO ledger: stable URLs + honest lastmod across full rebuilds ────

def content_hash(tr: dict) -> str:
    """Fingerprint the meaningful, user-visible content of a track page.

    Ignores template/CSS churn on purpose — only real content changes
    (title/artist/year/role/feat/album/cover/notes) bump the fingerprint,
    so a cosmetic template edit doesn't reset every page's <lastmod>.
    """
    payload = json.dumps(
        {
            "artist": tr.get("artist", ""), "title": tr.get("title", ""),
            "year": tr.get("year", ""), "role": tr.get("role", ""),
            "feat": tr.get("feat", ""), "album": tr.get("album", ""),
            "img": tr.get("img", ""), "notes": notes_for(tr),
        },
        ensure_ascii=False, sort_keys=True,
    )
    return hashlib.sha1(payload.encode("utf-8")).hexdigest()[:16]


def render_redirect(target_slug: str) -> str:
    """A retired slug's page: canonical + instant redirect to the live URL.

    Google treats a same-host meta-refresh(0)+canonical as a 301, so link
    equity from an old URL flows to the renamed track instead of 404-ing.
    """
    url = f"{SITE}/track/{target_slug}/"
    return (
        '<!DOCTYPE html>\n<html lang="ru">\n<head>\n<meta charset="utf-8">\n'
        f'<title>Переехало → {esc(target_slug)}</title>\n'
        f'<link rel="canonical" href="{esc(url)}">\n'
        f'<meta http-equiv="refresh" content="0; url={esc(url)}">\n'
        f'<script>location.replace({json.dumps(url)});</script>\n'
        f'</head>\n<body>\n<p>Страница переехала: <a href="{esc(url)}">{esc(url)}</a></p>\n'
        '</body>\n</html>\n'
    )


def sync_seo_state(tracks: list[dict]) -> tuple[dict, dict]:
    """Reconcile the persistent SEO ledger against the current track set.

    Returns (lastmod_by_slug, redirects). A renamed track (same data-id,
    new slug) retires its old slug into `redirects`; a removed track is
    left to 404. Chains collapse to the final live slug; redirects whose
    key is now a live slug or whose target is gone are dropped.
    """
    try:
        state = json.loads(SEO_STATE_FILE.read_text(encoding="utf-8"))
    except (FileNotFoundError, ValueError):
        state = {}
    prev_ids = state.get("ids", {})
    prev_dates = state.get("dates", {})
    redirects = dict(state.get("redirects", {}))

    live_slugs = {tr["slug"] for tr in tracks}
    cur_ids = {tr["id"]: tr["slug"] for tr in tracks}

    # retire slugs of tracks that changed slug but still exist
    for tid, old_slug in prev_ids.items():
        new_slug = cur_ids.get(tid)
        if new_slug and new_slug != old_slug:
            redirects[old_slug] = new_slug

    # collapse chains a→b→c into a→c
    def resolve(slug: str, _seen: set) -> str:
        while slug in redirects and slug not in _seen:
            _seen.add(slug)
            slug = redirects[slug]
        return slug

    redirects = {old: resolve(dst, {old}) for old, dst in redirects.items()}
    # drop redirects that collide with a live page or point nowhere live
    redirects = {
        old: dst for old, dst in redirects.items()
        if old not in live_slugs and dst in live_slugs
    }

    # honest lastmod: keep stored date unless content fingerprint changed
    dates: dict[str, str] = {}
    new_dates: dict[str, dict] = {}
    for tr in tracks:
        slug, h = tr["slug"], content_hash(tr)
        prev = prev_dates.get(slug)
        lastmod = prev["lastmod"] if prev and prev.get("hash") == h else TODAY
        dates[slug] = lastmod
        new_dates[slug] = {"hash": h, "lastmod": lastmod}

    SEO_STATE_FILE.write_text(
        json.dumps(
            {"ids": cur_ids, "redirects": redirects, "dates": new_dates},
            ensure_ascii=False, indent=1, sort_keys=True,
        ) + "\n",
        encoding="utf-8",
    )
    return dates, redirects


def _sitemap_url(rel: str, lastmod: str, changefreq: str, priority: str) -> list[str]:
    """One <url> for the RU page and, once the EN mirror exists, one for
    /en/<rel> (same lastmod: the EN page is a rendering of the same data)."""
    lines = []
    for loc in (f"{SITE}/{rel}", *([f"{SITE}/en/{rel}"] if en_exists(rel) else [])):
        lines += [
            "  <url>", f"    <loc>{loc}</loc>", f"    <lastmod>{lastmod}</lastmod>",
            f"    <changefreq>{changefreq}</changefreq>",
            f"    <priority>{priority}</priority>", "  </url>",
        ]
    return lines


def write_sitemap(tracks: list[dict], dates: dict) -> None:
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
        *_sitemap_url("", TODAY, "weekly", "1.0"),
        *_sitemap_url("track/", TODAY, "weekly", "0.9"),
        # /faq/ is hand-written (not generated from tracks) — its lastmod must reflect
        # when the FAQ text actually changed, not every rebuild. Bump FAQ_LASTMOD by hand.
        *_sitemap_url("faq/", FAQ_LASTMOD, "monthly", "0.8"),
        *_sitemap_url("tier/", TIER_LASTMOD, "monthly", "0.8"),
    ]
    for tr in tracks:
        lines += _sitemap_url(f"track/{tr['slug']}/", dates.get(tr["slug"], TODAY),
                              "monthly", "0.7")
    lines.append("</urlset>")
    (ROOT / "sitemap.xml").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    global NOTES
    roles = load_roles()
    NOTES = load_notes()
    doc = INDEX.read_text(encoding="utf-8")
    tracks = extract_tracks(doc, roles)
    assign_slugs(tracks)
    attach_related(tracks)

    hub_file = TRACK_DIR / "index.html"
    if TRACK_DIR.exists():
        if hub_file.is_file():
            hub_file.unlink()
        for old in TRACK_DIR.iterdir():
            if old.is_dir():
                for f in old.iterdir():
                    f.unlink()
                old.rmdir()
    TRACK_DIR.mkdir(exist_ok=True)

    live_slugs = {tr["slug"] for tr in tracks}
    for tr in tracks:
        out = TRACK_DIR / tr["slug"]
        out.mkdir(parents=True, exist_ok=True)
        (out / "index.html").write_text(render_page(tr), encoding="utf-8")

    # reconcile SEO ledger, then re-emit redirect stubs for retired slugs
    # (the track/ wipe above deletes them each build, so rebuild from state)
    dates, redirects = sync_seo_state(tracks)
    for old_slug, new_slug in redirects.items():
        if old_slug in live_slugs:
            continue
        out = TRACK_DIR / old_slug
        out.mkdir(parents=True, exist_ok=True)
        (out / "index.html").write_text(render_redirect(new_slug), encoding="utf-8")

    hub_file.write_text(render_hub(tracks), encoding="utf-8")
    INDEX.write_text(patch_index_footer(doc, tracks), encoding="utf-8")

    counts = catalog_counts(tracks)
    patch_faq(counts)
    patch_llms_txt(counts)

    write_sitemap(tracks, dates)
    from collections import Counter
    print(f"Сгенерировано страниц: {len(tracks)}  роли: {dict(Counter(t['role'] for t in tracks))}")
    print(f"Счётчики: работ {counts['recordings']} · артистов (с соавторами и фитами) "
          f"{counts['artists']} · разделов хаба {counts['groups']}")
    if redirects:
        print(f"Редиректы (retired slugs): {len(redirects)}")

    # the EN mirror is a rendering of the pages just written; it runs here so
    # that one command keeps both sides in sync (`--no-en` to skip)
    if "--no-en" not in sys.argv:
        import subprocess
        sys.stdout.flush()
        r = subprocess.run([sys.executable, str(ROOT / "build_en.py")], cwd=ROOT)
        if r.returncode != 0:
            sys.exit(f"build_en.py завершился с кодом {r.returncode} — см. i18n/missing.txt")


if __name__ == "__main__":
    main()
