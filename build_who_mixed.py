def fix_studio_graph(graph: list[dict]) -> list[dict]:
    """Normalise the studio node in a page's @graph and add the founders.

    Idempotent: keeps @id, name, alternateName, url, sameAs, description,
    foundingDate/Location and anything else page-specific; only the type,
    the MusicGroup-only keys and the founder links change.
    """
    idx = next((i for i, n in enumerate(graph) if n.get("@id") == STUDIO_ID), None)
    if idx is None:
        raise SystemExit(f"studio node {STUDIO_ID} not found in JSON-LD graph")
    node = graph[idx]
    node["@type"] = "Organization"
    for key in MUSICGROUP_ONLY:
        node.pop(key, None)
    node["founder"] = [{"@id": p["@id"]} for p in FOUNDERS]
    present = {n.get("@id") for n in graph}
    persons = [dict(p) for p in FOUNDERS if p["@id"] not in present]
    # founders sit right after the studio; existing Person nodes stay put
    return graph[: idx + 1] + persons + graph[idx + 1:]


def plural(n: int, one: str, few: str, many: str) -> str:
    """Russian plural: 1 артист, 2 артиста, 5 артистов, 11 артистов."""
    if n % 10 == 1 and n % 100 != 11:
        return one
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return few
    return many


def catalog_counts(tracks: list[dict]) -> dict:
    """The two public catalogue metrics, computed once for every page.

    recordings — publishedRecordingsCount: unique published tracks (unique
        Spotify ids after tile/album dedup; an album container is not a
        recording and is not counted).
    artists — creditedArtistsCount: unique artists credited anywhere in the
        catalogue — primary artists, collab partners in the artist field
        ("MACAN, NAVAI" → both) and featured artists from feats.json —
        after CANON spelling-variant merging and «*» marker stripping.
    groups — artistGroupsCount: sections of the /track/ hub, i.e. unique
        primary (first-credited) artists. Smaller than `artists` by design.
    """
    return {
        "recordings": len({tr["id"] for tr in tracks}),
        "artists": len(credited_artists(tracks)),
        "groups": len({primary_of(tr["artist"]) for tr in tracks}),
    }


def credited_artists(tracks: list[dict]) -> list[str]:
    """Every artist credited in the catalogue (see catalog_counts), sorted."""
    names: set[str] = set()
    for tr in tracks:
        names.update(canon(x) for x in tr["artist"].split(", "))
        names.update(feat_of(tr))
    names.discard("")
    return sorted(names, key=str.casefold)


