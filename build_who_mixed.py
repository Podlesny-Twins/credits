def album_note_key(artist: str, album: str) -> str:
    """Stable key for a story that belongs to a release as a whole."""
    return f"album-{slugify(primary_of(artist), album)}"


def notes_for(tr: dict) -> list[str]:
    """Release context first, then the track-specific interview answer."""
    paragraphs: list[str] = []
    if tr.get("album"):
        paragraphs.extend(NOTES.get(album_note_key(tr["artist"], tr["album"]), []))
    paragraphs.extend(NOTES.get(tr.get("slug", ""), []))
    return paragraphs


def linkify(text: str) -> str:
    """Escape story copy while keeping supplied http(s) references useful.

    Trailing sentence punctuation is left outside the link: a URL that ends a
    sentence would otherwise carry the full stop into href and 404.
    """
    safe = esc(text)

    def wrap(m: re.Match) -> str:
        url = m.group(0)
        tail = re.search(r"[.,;:!?)»]+$", url)
        tail = tail.group(0) if tail else ""
        if tail:
            url = url[: -len(tail)]
        return f'<a href="{url}" rel="noopener" target="_blank">{url}</a>{tail}'

    return re.sub(r"https?://[^\s<]+", wrap, safe)


def story_details(paragraphs: list[str], label: str = "О работе над треком") -> str:
    if not paragraphs:
        return ""
    body = "".join(f"<p>{linkify(p)}</p>" for p in paragraphs)
    return (
        '<details class="story">'
        f'<summary>{esc(label)}</summary><div class="story-copy">{body}</div>'
        "</details>"
    )


def load_feats() -> dict:
    """Map track id -> featured artist(s) from feats.json. Value is a
    string ("SALUKI") or list (["SALUKI", "OG Buda"]); empty = no feat."""
    if not FEATS_FILE.is_file():
        return {}
    data = json.loads(FEATS_FILE.read_text(encoding="utf-8"))
    return {row["id"]: row["feat"] for row in data if row.get("feat")}


def extract_tracks(doc: str, roles: dict) -> list[dict]:
    tracks: list[dict] = []
    seen: set[str] = set()

    tile_re = re.compile(
        r'<button class="tile(?![^"]*album)[^"]*"[^>]*data-id="([A-Za-z0-9]{22})"[^>]*>'
        r'.*?<img src="([^"]+)"[^>]*>.*?<span class="art">(.*?)</span>'
        r'<span class="trk">(.*?)</span><span class="yr">(.*?)</span>',
        re.S,
    )
    for tid, img, artist, title, year in tile_re.findall(doc):
        artist = html.unescape(re.sub(r"<[^>]+>", "", artist))
        if tid in seen:
            continue
        seen.add(tid)
        tracks.append({
            "id": tid, "img": img, "artist": artist,
            "title": html.unescape(title), "year": html.unescape(year),
            "album": "", "role": roles.get(tid, "mix"),
        })

    feats = load_feats()
    albums = json.loads(re.search(r"var ALBUMS=(\[.*?\]);", doc, re.S).group(1))
    for album in albums:
        for tr in album["tracks"]:
            tid = tr["id"]
            if tid in seen:
                continue
            seen.add(tid)
            tracks.append({
                "id": tid, "img": album["cover"], "artist": album["artist"],
                "title": tr["title"], "year": tr.get("year", ""),
                "album": album["name"], "role": roles.get(tid, "mix"),
                "feat": feats.get(tid, tr.get("feat", "")),
            })

    return tracks


def assign_slugs(tracks: list[dict]) -> None:
    used: dict[str, int] = {}
    for tr in tracks:
        base = slugify(tr["artist"], tr["title"])
        n = used.get(base, 0)
        used[base] = n + 1
        tr["slug"] = base if n == 0 else f"{base}-{n + 1}"


# ── related works (внутренняя перелинковка) ──────────────────────────
#
# Страница трека раньше ссылалась только на хаб и FAQ, поэтому в Search
# Console у каждой стояло «Ссылающаяся страница: не найдено», а 179 из 220
# адресов висели в статусе «Обнаружена, не проиндексирована»: робот знал
# про них из sitemap, но не имел пути обхода и повода тратить бюджет.
# Соседи выбираются кольцом (не «первые пять»), чтобы входящие ссылки
# достались каждому треку, а не только началу списка артиста.

REL_MAX = 5


def _ring(seq: list[dict], start: int, n: int) -> list[dict]:
    """n соседей по кругу, начиная со следующего за start."""
    out = []
    for k in range(1, len(seq)):
        if len(out) >= n:
            break
        out.append(seq[(start + k) % len(seq)])
    return out


def attach_related(tracks: list[dict]) -> None:
    by_artist: "OrderedDict[str, list[dict]]" = OrderedDict()
    by_album: "OrderedDict[tuple, list[dict]]" = OrderedDict()
    for tr in tracks:
        by_artist.setdefault(primary_of(tr["artist"]), []).append(tr)
        if tr.get("album"):
            by_album.setdefault((primary_of(tr["artist"]), tr["album"]), []).append(tr)

    for group in by_album.values():
        for i, tr in enumerate(group):
            tr["rel_album"] = _ring(group, i, REL_MAX)

    for group in by_artist.values():
        for i, tr in enumerate(group):
            same = tr.get("album") or ""
            pool = [
                t for t in group
                if t is not tr and not (same and (t.get("album") or "") == same)
            ]
            tr["rel_artist"] = _ring(pool, i % len(pool), REL_MAX) if pool else []

    # одиночки (единственная работа артиста) остались бы без ссылок вовсе —
    # им кольцо по всему каталогу, чтобы страница не была тупиком
    for i, tr in enumerate(tracks):
        if not tr.get("rel_album") and not tr.get("rel_artist"):
            tr["rel_any"] = _ring(tracks, i, 4)

    # Обратный проход: пулы у соседей разного размера, поэтому кольцо со
    # смещением само по себе не покрывает всех — часть треков осталась бы
    # без входящих ссылок, то есть ровно в том состоянии, ради которого всё
    # и затевалось. Донор — сосед по артисту с самым коротким списком.
    inbound: dict[str, int] = {}
    for tr in tracks:
        for t in (tr.get("rel_album", []) + tr.get("rel_artist", [])
                  + tr.get("rel_any", [])):
            inbound[t["slug"]] = inbound.get(t["slug"], 0) + 1
    for tr in tracks:
        if inbound.get(tr["slug"]):
            continue
        donors = [t for t in by_artist[primary_of(tr["artist"])] if t is not tr]
        if not donors:
            donors = [t for t in tracks if t is not tr]
        donor = min(donors, key=lambda t: len(t.get("rel_album", []))
                    + len(t.get("rel_artist", [])) + len(t.get("rel_any", [])))
        donor.setdefault("rel_artist", []).append(tr)
        inbound[tr["slug"]] = 1


